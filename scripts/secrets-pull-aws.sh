#!/usr/bin/env bash
# Generates .env.local from AWS Secrets Manager, the source of truth for secrets
# (docs/project_plan.md section 7). Run through `make secrets-pull-aws` (or the local- variant).
#
# Settings, from the environment first and then from .env.docker:
#   AWS_SECRET_ID  (required) the secret; its SecretString is a flat JSON object of variables
#   AWS_PROFILE    the AWS CLI profile (an IAM Identity Center / SSO profile in ~/.aws/config)
#   AWS_REGION     the secret's region, when the profile does not set it
# Also: ENV_FILE (default .env.local; relative paths are from the repository root), SECRETS_NODE (command that runs Node.js; default node),
# FORCE=1 to replace an existing ENV_FILE that this script did not generate.
#
# Requires the AWS CLI v2 on the host. Prints variable names only, never values.
set -euo pipefail

cd "$(dirname "$0")/.."
# shellcheck source=scripts/lib/aws-secrets.sh
source scripts/lib/aws-secrets.sh

secret_id="$(setting AWS_SECRET_ID)"
profile="$(setting AWS_PROFILE)"
region="$(setting AWS_REGION)"
env_file="${ENV_FILE:-.env.local}"
read -r -a node_cmd <<<"${SECRETS_NODE:-node}"

[[ -n "$secret_id" ]] || fail "AWS_SECRET_ID is not set (in .env.docker or the environment)."
command -v aws >/dev/null || fail "the AWS CLI v2 is required on the host: https://aws.amazon.com/cli/"
if [[ -e "$env_file" && "${FORCE:-}" != "1" ]] && ! is_managed "$env_file"; then
  fail "$env_file was not generated by this script; move it away or rerun with FORCE=1."
fi

aws_args=()
[[ -n "$profile" ]] && aws_args+=(--profile "$profile")
[[ -n "$region" ]] && aws_args+=(--region "$region")

ensure_aws_session ${aws_args[@]+"${aws_args[@]}"}

# umask keeps the temporary file private; mv replaces the target only once it is complete.
umask 077
tmp_file="$(mktemp "${env_file}.XXXXXX")"
trap 'rm -f "$tmp_file"' EXIT

fetch_secret "$secret_id" ${aws_args[@]+"${aws_args[@]}"} |
  "${node_cmd[@]}" scripts/secrets-to-env.ts --format env --source "$secret_id" >"$tmp_file"
chmod 600 "$tmp_file"
mv "$tmp_file" "$env_file"
trap - EXIT

echo "Wrote $env_file from $secret_id:"
grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "$env_file" | cut -d= -f1 | sed 's/^/  /'
